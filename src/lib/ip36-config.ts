/**
 * 根据ID获取计策详情
 */
export function getTechniqueById(techniqueId: string): IP36Technique | null {
  for (const category of IP36_CATEGORIES) {
    const technique = category.techniques.find(t => t.id === techniqueId);
    if (technique) return technique;
  }
  return null;
}

/**
 * 根据类别ID获取类别详情
 */
export function getCategoryById(categoryId: string): IP36Category | null {
  return IP36_CATEGORIES.find(c => c.id === categoryId) || null;
}


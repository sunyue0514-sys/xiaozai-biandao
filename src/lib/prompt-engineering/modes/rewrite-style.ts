/**
 * 构建完整的仿写提示词
 */
export function buildRewriteStylePrompt(
  hasCustomerProfile: boolean
): string {
  if (hasCustomerProfile) {
    // 有创作者档案：强调身份映射
    return `${REWRITE_CORE_CONCEPT}

${REWRITE_EXECUTION_STEPS}

${REWRITE_EXAMPLES}

【当前任务：基于创作者档案仿写】

你正在进行有档案的仿写创作。

重要提醒：
1. 必须先执行"身份映射"，将参考内容的身份替换为创作者档案身份
2. 案例必须来自创作者的专业领域，不能照搬参考内容的案例
3. 表达风格必须符合创作者的人设特点
4. 目标用户必须是创作者的目标用户

仿写成功的关键：
- 看得出学的是哪条爆款（结构相似）
- 看得出是谁的内容（身份独特）
- 看不出是仿写（内容原创）

`;
  } else {
    // 无创作者档案：保留原风格
    return `${REWRITE_CORE_CONCEPT}

${REWRITE_EXECUTION_STEPS}

【当前任务：保留原风格仿写】

没有创作者档案时，仿写的重点是：
1. 学习参考内容的结构和技巧
2. 降维打击：用更简洁有力的语言重构
3. 本土化表达：符合中文短视频用户习惯

仿写成功的关键：
- 结构清晰完整
- 表达自然流畅
- 爆款基因完整

`;
  }
}

/**
 * 洗稿模式提示词
 * 
 * 与仿写的区别：洗稿保留原意，改写表达
 */
export const REWRITE_SOURCE_PROMPT = `【洗稿模式说明】

═══════════════════════════════════════════════════════════════
洗稿 vs 仿写
═══════════════════════════════════════════════════════════════

【洗稿】保留原意，改写表达
- 保留：核心观点、主要信息
- 改变：句式结构、用词方式
- 目的：降低重复率，保持原意

【仿写】学习结构，创作新内容
- 学习：叙事结构、技巧方法
- 替换：身份、案例、场景
- 目的：创作原创内容

═══════════════════════════════════════════════════════════════
洗稿模式选择
═══════════════════════════════════════════════════════════════

1. 高维同题再创作
   - 保留原文首句和核心主题
   - 改写中间内容，换一种表达方式
   - 加入新的观点和案例
   - 重复率控制在10%以内
   - 内容要更深入、更有价值

2. 定向差异化再创作
   - 保留开篇底层逻辑
   - 按照用户指导或知识库自由发挥
   - 加入差异化观点和内容
   - 形成独特的表达风格
   - 避免与原文雷同

3. 首句借势续写
   - 借用原文首句作为钩子开头
   - 迅速转向自己的业务方向
   - 用自己的逻辑和案例展开
   - 保持开篇吸引力
   - 内容要原创且贴合自身定位

═══════════════════════════════════════════════════════════════
洗稿执行要点
═══════════════════════════════════════════════════════════════

✅ 正确做法：
- 理解原文核心观点
- 用自己的话重新表达
- 保持内容完整性
- 添加个人见解

❌ 错误做法：
- 简单替换同义词
- 调整句子顺序就当原创
- 删除关键信息
- 生搬硬套不相关内容

`;

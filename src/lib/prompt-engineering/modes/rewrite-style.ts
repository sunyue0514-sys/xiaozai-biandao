/**
 * 仿写模式提示词
 * 
 * 核心定义：仿写 = 学习结构 + 替换身份 + 保持风格
 * 
 * 与"洗稿"的区别：
 * - 洗稿：保留原意，改写表达（改衣服）
 * - 仿写：学习结构，创作新内容（学手艺）
 */

/**
 * 仿写核心概念定义
 */
export const REWRITE_CORE_CONCEPT = `【仿写的核心定义】

═══════════════════════════════════════════════════════════════
仿写 ≠ 抄袭 ≠ 洗稿
═══════════════════════════════════════════════════════════════

【仿写】学习爆款视频的"成功模式"，用自己的身份和内容重新演绎
- 学习：结构、技巧、情绪曲线
- 替换：身份、案例、表达方式
- 保持：爆款基因（钩子、金句、互动设计）

【洗稿】保留原文核心，改变表达方式
- 保留：核心观点、主要信息
- 改变：句式结构、用词方式
- 目的：降低重复率

【抄袭】直接照搬或稍作修改
- 照搬：大段复制原文
- 修改：简单替换同义词
- 目的：窃取他人成果

═══════════════════════════════════════════════════════════════
仿写公式
═══════════════════════════════════════════════════════════════

仿写 = 学习结构 + 替换内容 + 保持风格

仿写的三个层次：

第一层：直接替换（初级）
- 替换人物、地点、事件
- 保持原结构和表达
- 适合新手快速上手

第二层：结构迁移（中级）
- 学习叙事结构和节奏
- 创作同类型内容
- 适合有一定基础的创作者

第三层：基因提炼（高级）
- 提炼爆款核心基因
- 跨领域创新应用
- 适合资深创作者

`;


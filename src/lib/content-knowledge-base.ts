/**
 * 根据开篇评分维度推荐钩子
 */
export function recommendHookForDimension(
  dimension: 'curiosity' | 'benefit' | 'emotion'
): HookType[] {
  return OPENING_TRIPLE_DIMENSION[dimension].hookTypes as HookType[];
}


/**
 * 根据脚本类型获取相关知识
 */
export function getKnowledgeForScriptType(scriptType: ScriptType) {
  const scriptKnowledge = SCRIPT_TYPE_KNOWLEDGE[scriptType];
  
  // 获取推荐的钩子
  const recommendedHooks = scriptKnowledge.recommendedHooks.map(
    hookKey => HOOK_KNOWLEDGE[hookKey]
  ).filter(Boolean);
  
  // 获取推荐的心理战术
  const recommendedTactics = scriptKnowledge.recommendedTactics.map(
    tacticKey => PSYCHOLOGICAL_TACTICS_KNOWLEDGE[tacticKey]
  ).filter(Boolean);
  
  return {
    script: scriptKnowledge,
    hooks: recommendedHooks,
    tactics: recommendedTactics,
  };
}


/**
 * 根据脚本类型获取部分约束
 */
export function getConstraintsForScriptType(scriptType: ScriptType): string {
  // 所有类型都需要语言风格约束
  let prompt = LANGUAGE_STYLE_CONSTRAINT.getPrompt();
  
  // 根据类型添加特定约束
  switch (scriptType) {
    case 'opinion':
      // 说观点需要案例设计、金句、结尾约束
      prompt += CASE_DESIGN_CONSTRAINT.getPrompt();
      prompt += QUOTE_CONSTRAINT.getPrompt();
      prompt += ENDING_CONSTRAINT.getPrompt();
      prompt += INTERACTION_CONSTRAINT.getPrompt();
      break;
    case 'knowledge':
      // 教知识需要细节画面、节奏控制
      prompt += DETAIL_CONSTRAINT.getPrompt();
      prompt += RHYTHM_CONSTRAINT.getPrompt();
      break;
    case 'story':
      // 讲故事需要细节画面、人设感
      prompt += DETAIL_CONSTRAINT.getPrompt();
      prompt += PERSONA_CONSTRAINT.getPrompt();
      break;
    case 'process':
      // 晒过程需要节奏控制、细节画面
      prompt += RHYTHM_CONSTRAINT.getPrompt();
      prompt += DETAIL_CONSTRAINT.getPrompt();
      break;
  }
  
  // 添加弹性说明
  prompt += CREATIVE_FLEXIBILITY_NOTE;
  
  return prompt;
}


